-- E1C staging PostgreSQL baseline. Execute only on an empty coordinator DB.
-- Requires PostgreSQL 15+; rollback via dropping dedicated staging database.
BEGIN;
CREATE TABLE e1c_authorities (
 repository_id VARCHAR(128) PRIMARY KEY,
 epoch INTEGER NOT NULL DEFAULT 0 CHECK (epoch >= 0),
 revision INTEGER NOT NULL DEFAULT 0 CHECK (revision >= 0),
 owner_session VARCHAR(128),
 owner_principal VARCHAR(128),
 expires_at TIMESTAMPTZ,
 accepted_sha VARCHAR(64),
 generation INTEGER NOT NULL DEFAULT 0 CHECK (generation >= 0),
 CHECK ((owner_session IS NULL AND owner_principal IS NULL AND expires_at IS NULL)
     OR (owner_session IS NOT NULL AND owner_principal IS NOT NULL AND expires_at IS NOT NULL))
);
CREATE TABLE e1c_candidates (
 id VARCHAR(64) PRIMARY KEY, repository_id VARCHAR(128) NOT NULL REFERENCES e1c_authorities(repository_id),
 submitted_by VARCHAR(128) NOT NULL, sha VARCHAR(64) NOT NULL, generation INTEGER NOT NULL,
 identity VARCHAR(128) NOT NULL, verified BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX ix_e1c_candidates_repository_id ON e1c_candidates(repository_id);
CREATE TABLE e1c_receipts (
 repository_id VARCHAR(128) NOT NULL REFERENCES e1c_authorities(repository_id),
 principal VARCHAR(128) NOT NULL, request_id VARCHAR(128) NOT NULL,
 request_hash VARCHAR(64) NOT NULL, response TEXT NOT NULL,
 PRIMARY KEY(repository_id, principal, request_id)
);
CREATE TABLE e1c_audit (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 repository_id VARCHAR(128) NOT NULL REFERENCES e1c_authorities(repository_id),
 revision INTEGER NOT NULL, action VARCHAR(32) NOT NULL,
 principal VARCHAR(128) NOT NULL, session VARCHAR(128),
 payload_hash VARCHAR(64) NOT NULL, UNIQUE(repository_id,revision)
);
CREATE TABLE e1c_outbox (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 repository_id VARCHAR(128) NOT NULL REFERENCES e1c_authorities(repository_id),
 revision INTEGER NOT NULL, candidate_id VARCHAR(64) NOT NULL REFERENCES e1c_candidates(id),
 projected BOOLEAN NOT NULL DEFAULT FALSE, UNIQUE(repository_id,revision)
);
COMMIT;
