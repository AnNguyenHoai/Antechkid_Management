"""Offline release integrity gate; NEVER reads a production workspace or secret.

Run after build_release.py packages an EXE:
  python scripts/verify_startup_release.py <package_dir> <approved_source_sha>

This verifies the *external* release assets only. The PyInstaller embedded
migration tree still needs a Windows EXE/UAT smoke test using copied SQLCipher
data; this script does not falsely certify a runtime boot.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path


def migration_digest(root: Path) -> str:
    """Stable hash of Alembic resources, excluding generated bytecode."""
    root = Path(root)
    names = [Path("alembic.ini")]
    names.extend(
        Path("migrations") / p.relative_to(root / "migrations")
        for p in sorted((root / "migrations").rglob("*"))
        if p.is_file() and p.suffix != ".pyc" and "__pycache__" not in p.parts
    )
    digest = hashlib.sha256()
    for rel in sorted(names, key=lambda p: p.as_posix()):
        path = root / rel
        if not path.is_file() or path.is_symlink():
            raise RuntimeError(f"Required migration asset is missing/unsafe: {rel}")
        digest.update(rel.as_posix().encode("utf-8") + b"\\0")
        with path.open("rb") as stream:
            for chunk in iter(lambda: stream.read(1024 * 1024), b""):
                digest.update(chunk)
        digest.update(b"\\0")
    return digest.hexdigest()


def verify_package(root: Path, approved_sha: str) -> dict:
    root = Path(root)
    if not re.fullmatch(r"[0-9a-fA-F]{40}", approved_sha):
        raise ValueError("Approved SHA must be a full 40-character commit")
    manifest_path = root / "RELEASE_MANIFEST.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("source_commit", "").lower() != approved_sha.lower():
        raise RuntimeError("Source commit mismatch: release is not approved")
    if manifest.get("platform") != "windows-x64":
        raise RuntimeError("Unexpected release platform")
    if manifest.get("migration_sha256") != migration_digest(root):
        raise RuntimeError("Packaged migration tree does not match signed manifest")
    for required in ("CenterManager.exe", "AdminTools/GitProvisioningAdmin.exe",
                     "git/cmd/git.exe", "alembic.ini", "migrations/env.py"):
        if not (root / required).is_file():
            raise RuntimeError(f"Missing release artifact: {required}")
    forbidden_names = {
        "center.db", "config.json", "database_key.dpapi",
        "git_provisioning_private.json", "git_credentials.dpapi",
    }
    for path in root.rglob("*"):
        if path.is_symlink():
            raise RuntimeError("Symlinks not permitted in packaged release")
        if path.is_file() and (
            path.name.lower() in forbidden_names
            or path.suffix.lower() == ".dpapi"
            or ".git" in path.parts
        ):
            raise RuntimeError(f"Sensitive runtime material in release: {path.name}")
    return manifest


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if len(argv) != 2:
        print("usage: verify_startup_release.py <package-dir> <approved-full-SHA>")
        return 2
    try:
        manifest = verify_package(Path(argv[0]), argv[1])
    except (OSError, KeyError, ValueError, RuntimeError, json.JSONDecodeError) as exc:
        print(f"RELEASE BLOCKED: {exc}")
        return 1
    print(
        "RELEASE ASSETS VERIFIED (EXE/SQLCipher UAT STILL REQUIRED):",
        manifest["source_commit"],
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
